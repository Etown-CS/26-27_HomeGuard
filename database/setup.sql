-- ============================================================
-- HomeGuard database setup (Oracle SQL, 12c or newer)
-- Tables: users, devices, network, flagged
-- Safe to re-run: step 1 drops the old tables, step 2 rebuilds them.
-- WARNING: re-running deletes any data already in these tables.
-- ============================================================

-- ------------------------------------------------------------
-- 1. Drop existing tables (children first). Missing tables are ignored.
-- ------------------------------------------------------------
BEGIN
  FOR t IN (SELECT column_value AS name
              FROM TABLE(sys.odcivarchar2list('FLAGGED', 'NETWORK', 'DEVICES', 'USERS'))) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.name || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;   -- -942 = table does not exist
    END;
  END LOOP;
END;
/

-- ------------------------------------------------------------
-- 2. users
-- ------------------------------------------------------------
CREATE TABLE users (
    user_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fname       VARCHAR2(50)  NOT NULL,
    lname       VARCHAR2(50)  NOT NULL,
    email       VARCHAR2(255) NOT NULL,
    pwd_hash    VARCHAR2(255) NOT NULL,          -- store a salted hash, never the plain password
    created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id)
);

-- emails are unique regardless of upper/lower case
CREATE UNIQUE INDEX uq_users_email ON users (LOWER(email));

-- ------------------------------------------------------------
-- 3. devices: one user has many devices
-- ------------------------------------------------------------
CREATE TABLE devices (
    device_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id      NUMBER        NOT NULL,
    device_name  VARCHAR2(100) NOT NULL,
    device_type  VARCHAR2(30)  DEFAULT 'Other' NOT NULL,   -- Camera, Entertainment, Mobile, Computer, Smart home, Other
    ip           VARCHAR2(45)  NOT NULL,                   -- 45 chars fits IPv6
    mac          VARCHAR2(17),                             -- AA:BB:CC:DD:EE:FF
    paused       NUMBER(1)     DEFAULT 0 NOT NULL,         -- 1 = user pressed "Pause device"
    first_seen   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    last_active  TIMESTAMP,
    CONSTRAINT pk_devices PRIMARY KEY (device_id),
    CONSTRAINT fk_devices_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_devices_paused CHECK (paused IN (0, 1))
);

-- ------------------------------------------------------------
-- 4. network: a user's home network (kept as drawn: user_id and device_id are both foreign keys)
-- ------------------------------------------------------------
CREATE TABLE network (
    network_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id       NUMBER        NOT NULL,
    device_id     NUMBER,                                  -- optional link to a device
    ip            VARCHAR2(45),                            -- e.g. the router / gateway address
    network_name  VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_network PRIMARY KEY (network_id),
    CONSTRAINT fk_network_user   FOREIGN KEY (user_id)   REFERENCES users (user_id)     ON DELETE CASCADE,
    CONSTRAINT fk_network_device FOREIGN KEY (device_id) REFERENCES devices (device_id) ON DELETE SET NULL
);

-- ------------------------------------------------------------
-- 5. flagged: one row per anomaly the ML model flags.
--    The extra columns match the fields in alerts.json
--    (event_time = "timestamp", packet_length = "length"; renamed because those are Oracle keywords).
-- ------------------------------------------------------------
CREATE TABLE flagged (
    flagged_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id        NUMBER       NOT NULL,
    device_id      NUMBER,                                 -- empty if the source IP is not a known device
    status         VARCHAR2(10) DEFAULT 'FLAGGED' NOT NULL,
    resolved       NUMBER(1)    DEFAULT 0 NOT NULL,        -- 1 = user pressed "Mark as safe"
    event_time     TIMESTAMP    NOT NULL,
    src_ip         VARCHAR2(45) NOT NULL,
    dst_ip         VARCHAR2(45) NOT NULL,
    protocol       VARCHAR2(20),
    dst_port       NUMBER(5),
    packet_length  NUMBER,                                 -- bytes
    anomaly_score  NUMBER,                                 -- Isolation Forest score
    explanation    CLOB,                                   -- plain-language text from the LLM
    CONSTRAINT pk_flagged PRIMARY KEY (flagged_id),
    CONSTRAINT fk_flagged_user   FOREIGN KEY (user_id)   REFERENCES users (user_id)     ON DELETE CASCADE,
    CONSTRAINT fk_flagged_device FOREIGN KEY (device_id) REFERENCES devices (device_id) ON DELETE SET NULL,
    CONSTRAINT ck_flagged_status   CHECK (status IN ('FLAGGED', 'REVIEW', 'NORMAL')),
    CONSTRAINT ck_flagged_resolved CHECK (resolved IN (0, 1))
);

-- ------------------------------------------------------------
-- 6. Indexes for the dashboard lookups.
--    (Oracle does not index foreign keys automatically.)
-- ------------------------------------------------------------
CREATE INDEX ix_devices_user      ON devices (user_id);
CREATE INDEX ix_devices_ip        ON devices (ip);
CREATE INDEX ix_devices_mac       ON devices (mac);
CREATE INDEX ix_network_user      ON network (user_id);
CREATE INDEX ix_network_device    ON network (device_id);
CREATE INDEX ix_flagged_user_time ON flagged (user_id, event_time DESC);
CREATE INDEX ix_flagged_device    ON flagged (device_id);

